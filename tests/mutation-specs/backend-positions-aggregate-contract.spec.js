// that introduced the owner-run screen is deleted by this PR, so these are the
// only place those numbers still run. RAW_RUNS and SEAM_REJECTED matter most:
// they say the enumeration is exhaustive and the seam is fail-closed.
//
// ZERO-VALUED AND EMPTY PINS get the mutation that matters for them.
// MONOLITH_DEPENDENCIES, EVALUATION_TIME_READS, TOP_LEVEL_STATEMENT_LINES,
// OPENING_COMMENT_LINES and the eight fields of ZERO_DIRECTIONS are all zero or
// empty, and that is also what a metric measuring nothing returns — so each is
// mutated UP, to prove the contract reads a measurement rather than a constant.
// §3 carries the control on an input where the answer differs.
//
// MONOLITH_DEPENDENCIES is mutated to `['S']`. `S` is the const that
// disqualified audit #424 and that #455 narrowed the rule around, so it is the
// dependency whose presence would matter most — and this layer has none at all.
//
// PURE_ASCII_LAYERS is mutated UP for the same reason and one more: it is the
// single superlative this cycle makes, so a pin that could not fail would be
// the worst place in the file to have one.
//
// CALLERS and OWNERS_EXPECTED are mutated to OTHER REAL DECLARATIONS, not to
// misspellings: a name that exists is what tests the claim about which name is
// there, where a misspelling fails for the boring reason instead.
//
// Range, object and table literals are mutated by MOVING a value, never by
// extending them: an appended element perturbs nothing and survives. A mutant
// that edits a line INSIDE a multi-line literal cannot name its pin in the find
// text, so it declares `covers` instead, and the coverage contract checks that
// every declared name is a real pin.
//
// SITE_ENDS carries three mutants, one per row — the table is what says the cut
// stops at one owner and WHY, so a dropped or altered row is the failure it
// exists to prevent. CHAIN is mutated by REPLACING an entry, not appending one:
// the array is CHRONOLOGICAL, so an appended layer would also be a lie about
// the order.
//
// TWO CYCLES RUNNING, a pin written for the next phase shipped unread —
// OWNER_SIZES in #455, NET_REDUCTION and RESIDUAL_MONOLITH in #456. Both of the
// latter are asserted here in §1, and both carry mutants below.
// ─────────────────────────────────────────────────────────────────────────────
