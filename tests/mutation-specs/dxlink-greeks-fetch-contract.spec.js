// Mutation spec — DXLink greeks fetch PERMANENT boundary contract.
//
// One mutant per pinned constant. The coverage contract proves on every push
// that each `find` still appears exactly once in the target and that no pin is
// left uncovered, then applies all of them against a baseline it verifies green
// first. It is the NEWEST layer that carries a spec, and only the newest, so
// this one retires when the next layer ships.
//
// CARRIED OVER FROM THE AUDIT, because the contract re-executes the audit's
// measurements against the base it reconstructs rather than quoting them. The
// mutants that left are the ones whose constants described the audit ITSELF —
// its ratchet, its own path, the newest contract it measured growth against.
// What arrived describes the SHIPPED layer: the module, the tag, the chain it
// joined and the chain-wide counts that moved when it did.
//
// CHAIN IS MUTATED AS AN ORDER, not as a set: its last two entries are swapped,
// so a chain that holds the right layers in the wrong sequence fails. Length,
// membership and the tail were all checked before #459 and the sequence between
// them was not, which is how that mutant survived a whole pass.
//
// THE SPLIT DIRECTION IS THIS AUDIT'S FINDING and carries its heaviest mutants.
// The claim is that the ninth direction counts a foundation call and a chain
// call as one thing, so CHAIN_OUTBOUND is mutated UP — the reading under which
// this region really does reach into an already-extracted module and the
// recommendation collapses — and FOUNDATION_SITES is mutated DOWN to zero, the
// reading under which there was nothing to split in the first place.
//
// ONE_CONSUMER_RAW and ONE_CONSUMER_SPLIT are mutated to EACH OTHER'S value,
// which is the world in which the split changes nothing and the finding has
// nothing to report. SPLIT_SET drops its LAST element rather than its first:
// the set is asserted by equality and ordered largest-first, so dropping the
// first would also trip the "largest is the recommendation" clause and prove
// less about completeness.
//
// DECIDED_BY_FOUNDATION is the honesty of the finding, not its strength. The
// mutant raises it far enough to break the "under a hundredth of the clean set"
// comparison, because an audit that overstated how often its refinement matters
// would be the failure mode worth catching.
//
// CANARY_IN_RESULT is flipped to `false` — the reading in which the source
// comment is TRUE and there is no incidental defect. §7 drives the whole DXLink
// protocol against a fake socket to establish it, so this mutant proves that
// drive is load-bearing rather than decorative.
//
// LAYERS_CALLING_TTCALL and LAYERS_CALLING_FOUNDATION are counts over the
// shipped chain that the finding rests on, so each is mutated separately; the
// majority comparison in §5(b) means LAYERS_CALLING_FOUNDATION must be pushed
// below half rather than merely changed.
//
// ZERO-VALUED AND EMPTY PINS get the mutation that matters for them.
// TOP_LEVEL_STATEMENT_LINES and EVALUATION_TIME_READS are zero and empty, and
// that is also what a metric measuring nothing returns, so each is mutated UP.
// MONOLITH_DEPENDENCIES is empty here, so it is mutated to `['S']` — the name
// that disqualified audit #424 — which tests that the list is MEASURED rather
// than defaulted.
//
// SPLIT_SET_HOSTED_BY_CONSUMER is mutated to THREE, which is the number the
// first draft of this audit carried — inferred from the three candidates
// nearest to hand rather than counted. The mutant is the wrong answer that was
// actually written, which is the most useful mutant a pin can have.
//
// NAMES ARE MUTATED TO OTHER REAL DECLARATIONS, not to misspellings: a name
// that exists is what tests the claim about which name is there.
// ─────────────────────────────────────────────────────────────────────────────
