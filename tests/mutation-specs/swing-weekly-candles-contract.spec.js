// layer's seam unusual: MUTUAL_NAME, MUTUAL_INBOUND_SITE, MUTUAL_TARGET and
// MUTUAL_OUTBOUND_CALLS. MUTUAL_INBOUND_SITE is moved to ANOTHER REAL EDGE
// rather than to a nonsense offset — the assertion says that site is hosted by
// `_etWeekBucket`, and only a site hosted by something else tests it.
//
// ZERO-VALUED PINS get the mutation that matters for them. TOP_LEVEL_STATEMENT_-
// LINES, PRIVATE_OWNER_REFS_OUTSIDE and the eight fields of ZERO_DIRECTIONS are
// all `0`, and `0` is also what a metric that measures nothing returns — so each
// is mutated UP, to prove the contract reads a measurement rather than a
// constant. The controls that prove those metrics discriminate live in §5.
//
// PRIVATE_OWNER is mutated to ANOTHER OWNER of the same module rather than to a
// misspelling: `_swingWeekBucket` really is declared here, and it really is
// named from outside, so it is the input on which the "named nowhere else"
// claim must fail. A misspelling would fail for the boring reason instead.
//
// Range and object literals are mutated by MOVING a value, never by extending
// them: an appended element perturbs nothing and survives. A mutant that edits
// a line INSIDE a multi-line literal cannot name its pin in the find text, so it
// declares `covers` instead, and the coverage contract checks that every
// declared name is a real pin.
//
// CHAIN is mutated by REPLACING an entry, not by appending one: the array is
// CHRONOLOGICAL, so an appended layer would also be a lie about the order, and a
// replaced entry is the failure the list is there to prevent.
//
// SMALLEST_MODULE and REJECTED_LAYER are mutated to OTHER REAL MODULES in the
// chain, for the same reason: a path that ships is what tests the claim, and a
// path that does not would fail on existence rather than on rank or order.
// ─────────────────────────────────────────────────────────────────────────────
