// Mutation spec — portfolio technical merge PERMANENT boundary contract.
//
// One mutant per pinned constant. The coverage contract proves on every push
// that each `find` still appears exactly once in the target and that no pin is
// left uncovered, then applies all of them against a baseline it verifies green
// first.
//
// THE FINDING THIS LAYER CARRIES IS WHAT THE SPEC GUARDS HARDEST. The claim is
// that the nine-direction score counts SITES where the coupling is CONSUMERS,
// so DISTINCT_CONSUMERS, BY_CONSUMER, ONE_CONSUMER_CANDIDATES,
// ONE_CONSUMER_MULTI_SITE, BEST_BY_NINE_* and BEST_BY_CONSUMER_UNITS each carry
// a mutant, each moved in the direction that would make the finding LOOK true
// when it is not. BY_CONSUMER is mutated UP to 2, exactly the raw score: a
// contract that read the raw score and called it the consumer count would let
// that mutant live.
//
// THE PAIR PINS carry the alternative this cut declined, and the argument for
// stopping at one owner is that 5 > 1. PAIR_BY_CONSUMER is mutated DOWN to 1,
// which would make the two cuts look equally coupled and this one arbitrary.
//
// ZERO-VALUED PINS get the mutation that matters for them. TOP_LEVEL_STATEMENT_-
// LINES, MONOLITH_DEPENDENCIES, EVALUATION_TIME_READS and the eight fields of
// ZERO_DIRECTIONS are all zero or empty, and that is also what a metric
// measuring nothing returns — so each is mutated UP, to prove the contract reads
// a measurement rather than a constant. The controls that prove those metrics
// discriminate live in §3, §4 and §6, on inputs where the answer differs.
//
// MONOLITH_DEPENDENCIES is mutated to `['S']` specifically. `S` is the name that
// disqualified audit #424 and the one #455 narrowed the rule around, so it is
// the dependency whose presence would matter most — and this region has none,
// while the pair it declined has `S` among its three.
//
// NAMES ARE MUTATED TO OTHER REAL DECLARATIONS, not to misspellings: a name that
// exists is what tests the claim about which name is there, where a misspelling
// fails for the boring reason instead.
//
// THE CHAIN-WIDE COUNTS each get one. They are the numbers that go stale
// silently as the chain grows — CHAIN_LENGTH, LAYERS_ENDING_BRACE,
// LAYERS_WITH_SEPARATOR, LAYERS_WITH_RAW_PAIR, LAYERS_WITHOUT_SEPARATOR,
// PURE_ASCII_LAYERS, MODULE_SIZE_RANK and DOC_RANK — and each is asserted
// against a fresh walk of the chain rather than a remembered figure.
//
// Range, object and table literals are mutated by MOVING a value, never by
// extending them: an appended element perturbs nothing and survives. A mutant
// that edits a line INSIDE a multi-line literal cannot name its pin in the find
// text, so it declares `covers` instead, and the coverage contract checks that
// every declared name is a real pin.
// ─────────────────────────────────────────────────────────────────────────────
